/* CyberAudit Monitor — shared client runtime: API access, formatting, toasts,
   dialogs, the event drawer and the persistent top bar behaviour. */
(function () {
  "use strict";
  const CA = (window.CA = {});
  const csrf = document.querySelector('meta[name="csrf-token"]')?.content || "";
  const body = document.body;

  CA.role = body.dataset.role || "viewer";
  CA.username = body.dataset.user || "";
  CA.userId = Number(body.dataset.userId || 0);
  CA.poll = Number(body.dataset.poll || 3000);
  const RANK = { viewer: 1, analyst: 2, admin: 3 };
  CA.can = (role) => (RANK[CA.role] || 0) >= RANK[role];
  CA.reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (CA.reduceMotion) document.documentElement.classList.add("reduce-motion");

  CA.$ = (sel, root = document) => root.querySelector(sel);
  CA.$$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));
  CA.esc = (value) => String(value ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  CA.icon = (name, cls = "") => `<svg class="i ${cls}" aria-hidden="true"><use href="#i-${name}"></use></svg>`;

  /* ---------- API ---------- */
  CA.api = async function (url, { method = "GET", body: payload, signal } = {}) {
    const opts = { method, headers: { Accept: "application/json" }, credentials: "same-origin", signal };
    if (payload !== undefined) {
      opts.headers["Content-Type"] = "application/json";
      opts.body = JSON.stringify(payload);
    }
    if (method !== "GET") opts.headers["X-CSRF-Token"] = csrf;
    let res;
    try {
      res = await fetch(url, opts);
    } catch (err) {
      if (err.name === "AbortError") throw err;
      const e = new Error("Cannot reach the server. Check that the application is still running.");
      e.network = true;
      throw e;
    }
    if (res.status === 401) {
      window.location.href = "/login?next=" + encodeURIComponent(location.pathname + location.search);
      throw new Error("Your session has expired.");
    }
    let data = null;
    try { data = await res.json(); } catch (_) { /* non-JSON */ }
    if (!res.ok) {
      const e = new Error((data && data.error) || `Request failed (HTTP ${res.status}).`);
      e.status = res.status;
      e.field = data && data.field;
      throw e;
    }
    return data;
  };
  CA.query = (obj) => {
    const p = new URLSearchParams();
    Object.entries(obj).forEach(([k, v]) => { if (v !== undefined && v !== null && v !== "") p.set(k, v); });
    const s = p.toString();
    return s ? "?" + s : "";
  };

  /* ---------- formatting ---------- */
  const nf = new Intl.NumberFormat("en-US");
  CA.num = (n) => nf.format(Math.round(Number(n) || 0));
  const d = (iso) => new Date(iso);
  CA.time = (iso) => iso ? d(iso).toLocaleTimeString("en-GB", { hour: "2-digit", minute: "2-digit", second: "2-digit" }) : "—";
  CA.date = (iso) => iso ? d(iso).toLocaleDateString("en-GB", { day: "2-digit", month: "short" }) : "—";
  CA.dateTime = (iso) => iso ? `${CA.date(iso)} ${CA.time(iso)}` : "—";
  CA.fullDateTime = (iso) => iso ? d(iso).toLocaleString("en-GB", { year: "numeric", month: "short", day: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit" }) : "—";
  CA.tzLabel = (() => { const off = -new Date().getTimezoneOffset(); const s = off >= 0 ? "+" : "-"; const a = Math.abs(off); return `UTC${s}${Math.floor(a / 60)}${a % 60 ? ":" + String(a % 60).padStart(2, "0") : ""}`; })();
  CA.ago = (iso) => {
    if (!iso) return "—";
    const s = Math.max(0, Math.round((Date.now() - d(iso).getTime()) / 1000));
    if (s < 60) return `${s}s ago`;
    if (s < 3600) return `${Math.floor(s / 60)} min ago`;
    if (s < 86400) return `${Math.floor(s / 3600)} h ago`;
    return `${Math.floor(s / 86400)} d ago`;
  };
  CA.cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : "");
  CA.pill = (kind, text) => `<span class="pill ${CA.esc(kind)}">${CA.esc(text ?? kind)}</span>`;
  const ORIGIN = { seed: "Demo seed", simulated: "Simulated", live: "Live" };
  CA.originPill = (o) => `<span class="pill origin ${CA.esc(o)}" title="${o === "simulated" ? "Generated by the Event Simulator" : o === "seed" ? "Seeded demonstration record" : "Recorded from real use of this application"}">${ORIGIN[o] || o}</span>`;
  CA.localDayIso = (value, endOfDay) => {
    if (!value) return "";
    const dt = new Date(value + (endOfDay ? "T23:59:59" : "T00:00:00"));
    return isNaN(dt) ? "" : dt.toISOString().replace(/\.\d{3}Z$/, "Z");
  };

  /* ---------- motion helpers ---------- */
  CA.countUp = function (el, to, duration = 1100) {
    const target = Number(to) || 0;
    const from = Number(el.dataset.value || 0);
    el.dataset.value = String(target);
    if (CA.reduceMotion || from === target) { el.textContent = CA.num(target); return; }
    const start = performance.now();
    const step = (now) => {
      const p = Math.min(1, (now - start) / duration);
      el.textContent = CA.num(from + (target - from) * (1 - Math.pow(1 - p, 3)));
      if (p < 1) requestAnimationFrame(step);
    };
    requestAnimationFrame(step);
  };
  CA.debounce = (fn, ms = 300) => { let t; return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); }; };
  CA.busy = (btn, on, label) => {
    if (!btn) return;
    if (on) {
      btn.dataset.html = btn.innerHTML;
      btn.disabled = true;
      btn.innerHTML = `<span class="spinner"></span>${CA.esc(label || "Working…")}`;
    } else if (btn.dataset.html !== undefined) {
      btn.disabled = false;
      btn.innerHTML = btn.dataset.html;
      delete btn.dataset.html;
    }
  };

  /* ---------- toasts ---------- */
  const TOAST_ICON = { success: "check", error: "x-circle", info: "info", warn: "alert" };
  CA.toast = function (type, title, detail, timeout = 5000) {
    const host = document.getElementById("toasts");
    if (!host) return;
    const el = document.createElement("div");
    el.className = `toast ${type}`;
    el.setAttribute("role", type === "error" ? "alert" : "status");
    el.innerHTML = `${CA.icon(TOAST_ICON[type] || "info")}<div><div class="t-title">${CA.esc(title)}</div>${detail ? `<div class="t-detail">${CA.esc(detail)}</div>` : ""}</div><button class="t-close" type="button" aria-label="Dismiss">×</button>`;
    const close = () => { el.classList.add("leaving"); setTimeout(() => el.remove(), 260); };
    el.querySelector(".t-close").addEventListener("click", close);
    host.appendChild(el);
    while (host.children.length > 4) host.firstElementChild.remove();
    if (timeout) setTimeout(close, timeout);
  };

  /* ---------- modal layer (dialog + drawer) with focus trap ---------- */
  CA.openLayer = function (kind, html, { label = "", onClose } = {}) {
    const previous = document.activeElement;
    const scrim = document.createElement("div");
    scrim.className = "scrim";
    const panel = document.createElement("div");
    panel.className = kind;
    panel.setAttribute("role", "dialog");
    panel.setAttribute("aria-modal", "true");
    if (label) panel.setAttribute("aria-label", label);
    panel.innerHTML = html;
    document.body.append(scrim, panel);
    const focusables = () => CA.$$('button:not([disabled]), [href], input:not([disabled]), select, textarea, [tabindex]:not([tabindex="-1"])', panel);
    const close = () => {
      document.removeEventListener("keydown", onKey, true);
      scrim.remove();
      panel.remove();
      if (previous && previous.focus) previous.focus();
      if (onClose) onClose();
    };
    const onKey = (e) => {
      if (e.key === "Escape") { e.preventDefault(); close(); }
      if (e.key === "Tab") {
        const f = focusables();
        if (!f.length) return;
        const first = f[0], last = f[f.length - 1];
        if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
        else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
      }
    };
    document.addEventListener("keydown", onKey, true);
    scrim.addEventListener("click", close);
    CA.$$("[data-close]", panel).forEach((b) => b.addEventListener("click", close));
    setTimeout(() => (CA.$("[autofocus]", panel) || focusables()[0] || panel).focus(), 30);
    return { panel, close };
  };

  CA.confirm = function ({ title, message, confirmLabel = "Confirm", danger = false }) {
    return new Promise((resolve) => {
      let answered = false;
      const layer = CA.openLayer("dialog", `
        <h2>${CA.esc(title)}</h2>
        <p class="muted" style="margin:0;line-height:1.6">${CA.esc(message)}</p>
        <div class="actions"><button class="btn btn-ghost" type="button" data-close>Cancel</button>
        <button class="btn ${danger ? "btn-danger" : "btn-primary"}" type="button" data-ok autofocus>${CA.esc(confirmLabel)}</button></div>`,
        { label: title, onClose: () => { if (!answered) resolve(false); } });
      layer.panel.querySelector("[data-ok]").addEventListener("click", () => { answered = true; layer.close(); resolve(true); });
    });
  };

  CA.copy = async function (text, btn) {
    try {
      await navigator.clipboard.writeText(text);
    } catch (_) {
      const ta = document.createElement("textarea");
      ta.value = text; ta.style.position = "fixed"; ta.style.opacity = "0";
      document.body.appendChild(ta); ta.select();
      try { document.execCommand("copy"); } catch (__) { /* ignore */ }
      ta.remove();
    }
    if (btn) {
      const html = btn.innerHTML;
      btn.innerHTML = `${CA.icon("check", "i-sm")}Copied`;
      btn.classList.add("copied");
      setTimeout(() => { btn.innerHTML = html; btn.classList.remove("copied"); }, 1500);
    }
    CA.toast("success", "Copied to clipboard", text, 2200);
  };

  /* ---------- event detail drawer (shared by every page) ---------- */
  CA.eventRow = (e, { compact = false } = {}) => `
    <span class="mono dim">${CA.esc(CA.time(e.ts))}</span>
    <span class="mono">${CA.esc(e.uid)}</span>
    <span style="flex:1;min-width:0">${CA.esc(e.actor)} · ${CA.esc(e.action_label)}</span>
    ${compact ? "" : CA.pill(e.outcome)}`;

  CA.openEvent = async function (eventRef) {
    const layer = CA.openLayer("drawer", `
      <div class="drawer-head"><span class="section-label">Event details</span>
        <button class="icon-btn" type="button" data-close aria-label="Close event details">${CA.icon("x")}</button></div>
      <div class="drawer-body"><div class="skeleton" style="height:28px;width:60%"></div><div class="skeleton" style="height:80px"></div><div class="skeleton" style="height:180px"></div></div>`,
      { label: "Event details" });
    const bodyEl = layer.panel.querySelector(".drawer-body");
    try {
      const data = await CA.api(`/api/events/${encodeURIComponent(eventRef)}`);
      const e = data.event;
      const meta = JSON.stringify(e.metadata, null, 2);
      bodyEl.innerHTML = `
        <div style="display:flex;align-items:center;gap:10px;flex-wrap:wrap">
          <span class="mono" style="font-size:18px;font-weight:500">${CA.esc(e.uid)}</span>
          <button class="btn btn-sm btn-ghost" type="button" data-copy>${CA.icon("copy", "i-sm")}Copy ID</button>
          <span style="margin-left:auto;display:flex;gap:6px;flex-wrap:wrap">${CA.pill(e.outcome)}${CA.pill(e.severity)}${CA.originPill(e.origin)}</span>
        </div>
        <p class="callout" style="margin:0">${CA.esc(e.message)}</p>
        <dl class="kv">
          <dt>UTC timestamp</dt><dd class="mono">${CA.esc(e.ts)}</dd>
          <dt>Local time</dt><dd class="mono">${CA.esc(CA.fullDateTime(e.ts))} <span class="dim">${CA.tzLabel}</span></dd>
          <dt>Actor</dt><dd>${CA.esc(e.actor)}${e.actor_role ? ` <span class="dim">· ${CA.esc(e.actor_role)}</span>` : ""}</dd>
          <dt>Action</dt><dd>${CA.esc(e.action_label)} <span class="mono dim">${CA.esc(e.action)}</span></dd>
          <dt>Resource</dt><dd class="mono">${CA.esc(e.resource || "—")}</dd>
          <dt>Request</dt><dd class="mono">${e.http_method ? CA.esc(e.http_method + " " + (e.route || "")) : "—"}</dd>
          <dt>Source IP</dt><dd class="mono">${CA.esc(e.source_ip || "—")}${e.origin !== "live" && e.source_ip ? ' <span class="dim" style="font-family:var(--font)">· simulated label, not geolocated</span>' : ""}</dd>
          <dt>Outcome</dt><dd>${CA.esc(CA.cap(e.outcome))}</dd>
          <dt>Severity</dt><dd>${CA.esc(CA.cap(e.severity))}</dd>
        </dl>
        <div class="stack" style="gap:8px">
          <div class="section-label">Structured metadata</div>
          <pre class="code">${CA.esc(meta)}</pre>
          <div class="note-text">Passwords, session tokens and CSRF values are never written to the audit log.</div>
        </div>
        <div class="stack" style="gap:8px">
          <div class="section-label">Integrity</div>
          <div class="mono dim" style="font-size:11px;overflow-wrap:anywhere">hash ${CA.esc(e.hash)}<br>prev ${CA.esc(e.prev_hash)}</div>
        </div>
        <div class="stack" style="gap:8px">
          <div class="section-label">Related alerts</div>
          ${data.related_alerts.length ? data.related_alerts.map((a) => `
            <a class="entity" href="/alerts/${CA.esc(a.uid)}"><span class="mono" style="color:var(--red-text)">${CA.esc(a.uid)}</span>
            <span>${CA.esc(a.title)}</span><span class="meta">${a.is_trigger ? "trigger · " : ""}${CA.esc(a.status)}</span></a>`).join("")
            : '<div class="note-text">This event is not linked to any alert.</div>'}
        </div>
        <div class="stack" style="gap:6px">
          <div class="section-label">Neighbouring events (same actor or IP)</div>
          ${data.neighbours.map((n) => `<button type="button" class="entity" data-ev="${n.id}" style="background:${n.id === e.id ? "#0E2038" : "transparent"};cursor:pointer;text-align:left;width:100%;gap:10px">${CA.eventRow(n)}</button>`).join("")}
        </div>`;
      bodyEl.querySelector("[data-copy]").addEventListener("click", (ev) => CA.copy(e.uid, ev.currentTarget));
      CA.$$("[data-ev]", bodyEl).forEach((b) => b.addEventListener("click", () => {
        if (Number(b.dataset.ev) === e.id) return;
        layer.close();
        CA.openEvent(b.dataset.ev);
      }));
    } catch (err) {
      bodyEl.innerHTML = `<div class="error-box">${CA.esc(err.message)}</div>`;
    }
  };

  /* ---------- top bar behaviour ---------- */
  function setupClock() {
    const el = document.getElementById("clock");
    if (!el) return;
    const tick = () => {
      const now = new Date();
      el.textContent = now.toLocaleDateString("en-GB", { weekday: "short", day: "2-digit", month: "short" }) + " · " +
        now.toLocaleTimeString("en-GB", { hour: "2-digit", minute: "2-digit", second: "2-digit" });
    };
    tick();
    setInterval(tick, 1000);
  }

  CA.health = null;
  const healthListeners = [];
  CA.onHealth = (fn) => { healthListeners.push(fn); if (CA.health) fn(CA.health); };
  async function pollHealth() {
    const pill = document.getElementById("backendStatus");
    try {
      const h = await CA.api("/api/health");
      CA.health = h;
      if (pill) { pill.className = "status-pill ok"; pill.querySelector(".txt").textContent = "Backend connected"; }
      const badge = document.getElementById("navAlertCount");
      if (badge) {
        badge.textContent = h.unresolved_alerts.total;
        badge.classList.toggle("hidden", !h.unresolved_alerts.total);
      }
    } catch (err) {
      CA.health = { error: err.message };
      if (pill) { pill.className = "status-pill bad"; pill.querySelector(".txt").textContent = "Backend unavailable"; }
    }
    healthListeners.forEach((fn) => fn(CA.health));
  }
  CA.refreshHealth = pollHealth;

  function popover(btnId, panelId, onOpen) {
    const btn = document.getElementById(btnId), panel = document.getElementById(panelId);
    if (!btn || !panel) return;
    const close = () => { panel.classList.add("hidden"); btn.setAttribute("aria-expanded", "false"); };
    btn.addEventListener("click", (e) => {
      e.stopPropagation();
      const open = panel.classList.contains("hidden");
      CA.$$(".popover").forEach((p) => p.classList.add("hidden"));
      if (open) { panel.classList.remove("hidden"); btn.setAttribute("aria-expanded", "true"); if (onOpen) onOpen(); }
      else close();
    });
    document.addEventListener("click", (e) => { if (!panel.contains(e.target)) close(); });
    document.addEventListener("keydown", (e) => { if (e.key === "Escape" && !panel.classList.contains("hidden")) { close(); btn.focus(); } });
  }

  async function loadNotifications(markSeen) {
    const list = document.getElementById("notifList");
    const count = document.getElementById("notifCount");
    try {
      const data = await CA.api("/api/notifications");
      if (count) { count.textContent = data.unread > 9 ? "9+" : data.unread; count.classList.toggle("hidden", !data.unread); }
      const btn = document.getElementById("notifBtn");
      if (btn) btn.setAttribute("aria-label", `Notifications, ${data.unread} unread`);
      if (list) {
        list.innerHTML = data.items.length ? data.items.map((a) => `
          <a class="item" href="/alerts/${CA.esc(a.uid)}"><span class="${a.unread ? "unread-dot" : "read-dot"}"></span>
            <span style="flex:1;min-width:0"><span style="display:block;color:var(--text)">${CA.esc(a.title)}</span>
            <span class="meta">${CA.esc(a.uid)} · ${CA.esc(a.rule_id)} · ${CA.esc(CA.ago(a.created_at))}</span></span>
            ${CA.pill(a.severity)}</a>`).join("") : '<div class="empty">No alerts yet.</div>';
      }
      if (markSeen && data.unread) {
        await CA.api("/api/notifications/seen", { method: "POST", body: {} });
        if (count) count.classList.add("hidden");
      }
    } catch (err) {
      if (list) list.innerHTML = `<div class="error-box">${CA.esc(err.message)}</div>`;
    }
  }
  CA.refreshNotifications = () => loadNotifications(false);

  function setupSidebar() {
    const toggle = document.getElementById("menuToggle"), side = document.getElementById("sidebar");
    if (!toggle || !side) return;
    toggle.addEventListener("click", (e) => {
      e.stopPropagation();
      const open = side.classList.toggle("open");
      toggle.setAttribute("aria-expanded", String(open));
    });
    document.addEventListener("click", (e) => {
      if (side.classList.contains("open") && !side.contains(e.target)) { side.classList.remove("open"); toggle.setAttribute("aria-expanded", "false"); }
    });
  }

  function setupIntegrity() {
    const btn = document.getElementById("verifyChain");
    if (!btn) return;
    btn.addEventListener("click", async () => {
      CA.busy(btn, true, "Verifying…");
      try {
        const r = await CA.api("/api/integrity/verify", { method: "POST", body: {} });
        const dot = document.getElementById("chainDot"), title = document.getElementById("chainTitle"), detail = document.getElementById("chainDetail");
        dot.style.background = r.ok ? "var(--green)" : "var(--red)";
        title.textContent = r.ok ? "Audit chain verified" : "Integrity check failed";
        detail.textContent = r.ok ? `${CA.num(r.checked)} records · ${CA.time(r.verified_at)}` : `break at ${r.broken_at}`;
        if (r.ok) CA.toast("success", "Audit chain verified", `${CA.num(r.checked)} records recomputed; every hash and link matches.`);
        else CA.toast("error", "Audit chain broken", `${r.broken_at}: ${r.reason}`, 9000);
      } catch (err) {
        CA.toast("error", "Verification failed", err.message);
      } finally {
        CA.busy(btn, false);
      }
    });
  }

  document.addEventListener("keydown", (e) => {
    if (e.key === "/" && !/^(INPUT|TEXTAREA|SELECT)$/.test(document.activeElement.tagName)) {
      const s = document.getElementById("globalSearch");
      if (s) { e.preventDefault(); s.focus(); }
    }
  });

  if (document.getElementById("backendStatus")) {
    setupClock();
    setupSidebar();
    setupIntegrity();
    popover("notifBtn", "notifPanel", () => loadNotifications(true));
    popover("profileBtn", "profileMenu");
    pollHealth();
    setInterval(pollHealth, 15000);
    loadNotifications(false);
    setInterval(() => loadNotifications(false), 30000);
  }
})();
